-- reopen_task ----------------------------------------------------------------

-- Any member can reopen a completed or skipped occurrence. The occurrence generated
-- from it is withdrawn while it is still open; once it has been completed or skipped
-- the series has moved on and the reopen is refused (ALREADY_ADVANCED). An open task
-- must never be assigned to someone who has left, so a departed assignee (kept for
-- history while the task was closed) is cleared.
create or replace function public.reopen_task(p_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := (select auth.uid());
  v_hid uuid;
  v_next public.task_occurrences%rowtype;
begin
  if v_user is null then
    raise exception 'NOT_AUTHENTICATED' using errcode = 'P0001';
  end if;

  select o.household_id into v_hid
  from public.task_occurrences o
  where o.id = p_id;

  if not found then
    raise exception 'TASK_NOT_FOUND' using errcode = 'P0001';
  end if;

  perform 1 from public.households
  where id = v_hid and deleted_at is null
  for share;

  if not found or not private.is_member(v_hid) then
    raise exception 'TASK_NOT_FOUND' using errcode = 'P0001';
  end if;

  perform 1 from public.task_occurrences o
  where o.id = p_id
  for update;

  if not found then
    raise exception 'TASK_NOT_FOUND' using errcode = 'P0001';
  end if;

  select * into v_next
  from public.task_occurrences o
  where o.generated_from = p_id
  for update;

  if found then
    if v_next.completed_at is not null or v_next.skipped_at is not null then
      raise exception 'ALREADY_ADVANCED' using errcode = 'P0001';
    end if;
    delete from public.task_occurrences where id = v_next.id;
  end if;

  update public.task_occurrences o
  set completed_at = null,
      completed_by = null,
      skipped_at = null,
      skipped_by = null,
      assignee_id = case
        when o.assignee_id is not null and not exists (
          select 1
          from public.household_members m
          where m.household_id = v_hid
            and m.user_id = o.assignee_id
            and m.left_at is null
        ) then null
        else o.assignee_id
      end
  where o.id = p_id and (o.completed_at is not null or o.skipped_at is not null);
end;
$$;
